import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { readAsar, writeAsar } from '../asar.mjs';
import { install, restore } from '../patch.mjs';
import { outputRoot, fixtureInNewDirectory } from './fixture.mjs';
const root = outputRoot;
const dir = fs.mkdtempSync(path.join(root, 'lifecycle-test-'));
const target = path.join(dir, 'app.asar');
const original = fs.readFileSync(process.argv[2] || fixtureInNewDirectory().archive);
fs.writeFileSync(target, original);
const hash = p => crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
install(dir);
const first = hash(target);
install(dir);
assert.equal(hash(target), first, '重复安装必须幂等');
const metadata = JSON.parse(fs.readFileSync(path.join(dir, 'antigravity-zh-backup.json')));
const backup = path.join(dir, metadata.backupName);
const pristineBackup = fs.readFileSync(backup);
fs.appendFileSync(backup, 'corruption');
assert.throws(() => restore(dir), /备份校验失败/);
assert.equal(hash(target), first, '备份损坏时不得修改应用');
fs.writeFileSync(backup, pristineBackup);
restore(dir);
assert.ok(original.equals(fs.readFileSync(target)), '还原必须逐字节恢复原版');
const archive = readAsar(target);
const pkg = JSON.parse(archive.get('package.json').toString());
pkg.version += '-update-test';
const update = path.join(dir, 'update.asar');
writeAsar(archive, new Map([['package.json', Buffer.from(JSON.stringify(pkg))]]), update);
fs.copyFileSync(update, target);
assert.throws(() => restore(dir), /软件已更新/);
const updated = hash(target);
install(dir);
restore(dir);
assert.equal(hash(target), updated, '软件更新后必须恢复到新版本原版');
fs.writeFileSync(path.join(root, 'installation-verification.json'), JSON.stringify({passed:true,checks:['重复安装幂等','备份损坏拒绝还原','还原后与原版逐字节相同','拒绝跨版本还原','软件更新后独立备份并恢复新版本'],verifiedAt:new Date().toISOString()},null,2));
console.log('安装、重复安装、备份损坏保护、逐字节还原、跨版本保护和更新后备份测试全部通过。');
